"""Step 4: write the one-page findings note for management.

    python analytics/pipeline/findings.py

Reads the cleaned shipments and repeats the scenario arithmetic used on the web app's
Scenario page (src/data/scenario.ts) with the same default settings, so the note and the
dashboard agree. Small differences (a few tenths of a point) come from the 88 rows whose
delivery time was missing in the raw export: the app never sees that defect, this script does.

Writes analytics/reports/FINDINGS_FOR_MANAGEMENT.md
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
CLEAN = ROOT / "analytics/data/clean/shipments.csv"
OUT = ROOT / "analytics/reports/FINDINGS_FOR_MANAGEMENT.md"

NOW = pd.Timestamp("2026-10-25T04:00:00Z")
TARGET = 90.0
MIN_N = 20
LEVERS = {"carrier_shift": 0.30, "off_peak": 0.40, "eid_capacity": 0.50, "eid_premium": 0.08}
EIDS = pd.to_datetime(["2025-06-07", "2026-03-20", "2026-05-27"])
CARRIERS = {
    "PFL": "Padma Freight Lines", "MGT": "Meghna Transport", "KFM": "Karnaphuli Movers", "JMH": "Jamuna Haulage",
    "BLS": "Bay Link Shipping", "SSC": "Sundarban Sea Cargo", "SKY": "Skyway Cargo", "DAF": "Delta Air Freight",
}


def lakh(x: float) -> str:
    return f"৳{x / 1e5:,.1f} lakh"


def otd(df: pd.DataFrame) -> float:
    return 100 * df["on_time"].mean() if len(df) else 0.0


def load() -> pd.DataFrame:
    df = pd.read_csv(CLEAN, parse_dates=["dispatched_at", "promised_at", "delivered_at"])
    df = df[df["on_time"].notna()].copy()  # delivered and scored
    local = df["dispatched_at"].dt.tz_convert("Asia/Dhaka")
    df["peak"] = (df["mode"] == "road") & local.dt.hour.between(16, 21)
    day = local.dt.tz_localize(None).dt.normalize()
    to_eid = pd.concat([(e - day).dt.days for e in EIDS], axis=1)
    df["eid"] = to_eid.apply(lambda r: any(-4 <= d <= 10 for d in r), axis=1)
    df["monsoon"] = local.dt.month.between(6, 9)
    df["via_port"] = (df["origin_id"] == "CGP") | (df["destination_id"] == "CGP")
    return df


def window(df: pd.DataFrame, days: int) -> pd.DataFrame:
    return df[df["delivered_at"] > NOW - pd.Timedelta(days=days)]


def main() -> None:
    df = load()
    q = window(df, 90)
    year = window(df, 365)
    road = q[q["mode"] == "road"]

    base_n, base_late = len(q), int((q["on_time"] == 0).sum())
    base_otd = otd(q)
    base_cost = q["total_cost_bdt"].sum()

    # lever 1: carrier shift within each road lane
    moves = []
    for lane, g in road.groupby("lane_id"):
        c = g.groupby("carrier_id").agg(n=("on_time", "size"), otd=("on_time", "mean"), cps=("total_cost_bdt", "mean"))
        c = c[c["n"] >= MIN_N].sort_values("otd", ascending=False)
        if len(c) < 2:
            continue
        best, worst = c.iloc[0], c.iloc[-1]
        moved = LEVERS["carrier_shift"] * worst["n"]
        moves.append({
            "lane": lane, "from": c.index[-1], "to": c.index[0], "moved": moved,
            "from_otd": 100 * worst["otd"], "to_otd": 100 * best["otd"],
            "avoided": moved * (best["otd"] - worst["otd"]), "cost": moved * (best["cps"] - worst["cps"]),
        })
    moves = pd.DataFrame(moves).sort_values("avoided", ascending=False)
    carrier_avoided, carrier_cost = moves["avoided"].sum(), moves["cost"].sum()

    # lever 2: evening road dispatches moved earlier
    op_avoided = 0.0
    for _, g in road.groupby("lane_id"):
        peak, off = g[g["peak"]], g[~g["peak"]]
        if len(peak) < MIN_N or len(off) < MIN_N:
            continue
        op_avoided += LEVERS["off_peak"] * len(peak) * max(0.0, off["on_time"].mean() - peak["on_time"].mean())

    # lever 3: Eid capacity, measured over 12 months and spread over four quarters
    yroad = year[year["mode"] == "road"]
    eid, normal = yroad[yroad["eid"]], yroad[~yroad["eid"]]
    gap = max(0.0, normal["on_time"].mean() - eid["on_time"].mean())
    eid_avoided = LEVERS["eid_capacity"] * len(eid) * gap / 4
    eid_cost = LEVERS["eid_capacity"] * len(eid) * LEVERS["eid_premium"] * eid["total_cost_bdt"].mean() / 4

    avoided = carrier_avoided + op_avoided + eid_avoided
    proj_otd = 100 * ((base_n - base_late) + avoided) / base_n
    extra = carrier_cost + eid_cost

    port = q[q["via_port"]]
    port_share = 100 * len(port) / base_n
    port_late_share = 100 * (port["on_time"] == 0).sum() / base_late
    wet, dry = otd(year[year["monsoon"]]), otd(year[~year["monsoon"]])
    top = moves.iloc[0]

    lines = [
        "# Findings for management",
        "",
        f"Northgate Distribution (fictional), deliveries in the 90 days to 25 Oct 2026. Generated by `analytics/pipeline/findings.py`.",
        "",
        "## Where we are",
        "",
        f"- {base_otd:.1f}% on time against a {TARGET:.0f}% target: {base_late:,} late deliveries out of {base_n:,}.",
        f"- Lanes through Chattogram port carry {port_share:.0f}% of deliveries and {port_late_share:.0f}% of the late ones.",
        f"- Carrier choice is the biggest controllable factor. On {top['lane']}, {CARRIERS[top['to']]} ran {top['to_otd']:.0f}% on time and {CARRIERS[top['from']]} {top['from_otd']:.0f}%.",
        f"- Road on-time drops to {100 * eid['on_time'].mean():.0f}% around Eid, from {100 * normal['on_time'].mean():.0f}%. The monsoon months run {dry - wet:.0f} points below the rest of the year.",
        f"- Cost per delivery: ৳{base_cost / base_n:,.0f}.",
        "",
        "## What to change first (estimated per 90 days)",
        "",
        "| Change | Late deliveries avoided | Extra cost |",
        "|---|---:|---:|",
        f"| Move 30% of the weakest carrier's loads on each road lane to the best one | {carrier_avoided:.0f} | {lakh(carrier_cost)} |",
        f"| Move 40% of 4–9 pm truck dispatches to earlier in the day | {op_avoided:.0f} | none |",
        f"| Pre-book Eid trucks, closing half the Eid drop (8% premium) | {eid_avoided:.0f} | {lakh(eid_cost)} |",
        f"| **Together** | **{avoided:.0f}** | **{lakh(extra)}** |",
        "",
        f"On-time delivery would go from {base_otd:.1f}% to about {proj_otd:.1f}%, at {lakh(extra)} a quarter, "
        f"or ৳{extra / avoided:,.0f} per late delivery avoided. That does not reach {TARGET:.0f}%: most of the rest is port and highway congestion around Chattogram.",
        "",
        "## Carrier moves by lane",
        "",
        "| Lane | From | To | Loads moved | Avoided | Extra cost |",
        "|---|---|---|---:|---:|---:|",
    ]
    for _, m in moves.iterrows():
        lines.append(
            f"| {m['lane']} | {CARRIERS[m['from']]} ({m['from_otd']:.0f}%) | {CARRIERS[m['to']]} ({m['to_otd']:.0f}%) | {m['moved']:.0f} | {m['avoided']:.1f} | {lakh(m['cost'])} |"
        )
    lines += [
        "",
        "## Caveats",
        "",
        "- Simulated data. The method carries over to real data; the figures do not.",
        "- Assumes the better carrier has spare capacity and keeps its on-time rate with more volume.",
        "- Late-delivery penalties are not in the data, so only the cost side of each change has a taka figure.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {base_otd:.1f}% -> {proj_otd:.1f}%, {avoided:.0f} breaches avoided, {lakh(extra)}")


if __name__ == "__main__":
    main()
